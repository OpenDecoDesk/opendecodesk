// Builds a fresh local install of OpenDecoDesk for the end-to-end suite, and starts / stops it.
//
//   1. A local-only wrangler config (e2e/wrangler.e2e.toml, generated, git-ignored) from wrangler.toml:
//      no Workers AI binding, no cron trigger, the three R2 buckets switched on (wrangler dev simulates
//      them), ROOT_DOMAIN = "localhost" so admin.localhost is the admin and <shop>.localhost a shop.
//   2. e2e/.dev.vars (git-ignored) with freshly generated test secrets. No Stripe, Shippo or email keys.
//   3. A wiped state directory under the system temp folder (never under ~/Documents, which is synced).
//   4. The database built the way `npm run setup` builds a new one (schema.sql + the record that every
//      migration is in it), then `wrangler d1 migrations apply --local` (which must find nothing to do).
//   5. `wrangler dev` on 127.0.0.1:8897, waited for until it answers.
//
// Nothing here talks to Cloudflare: every wrangler command is --local.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

export const E2E_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const REPO = path.resolve(E2E_DIR, "..");
export const PORT = Number(process.env.E2E_PORT || 8897);
export const STATE_DIR = process.env.E2E_STATE_DIR || path.join(os.tmpdir(), "opendecodesk-e2e-" + PORT);
export const CONFIG = path.join(E2E_DIR, "wrangler.e2e.toml");
export const DEV_VARS = path.join(E2E_DIR, ".dev.vars");
export const AUTH_DIR = path.join(E2E_DIR, ".auth");
export const CREDENTIALS = path.join(AUTH_DIR, "credentials.json");
export const PID_FILE = path.join(AUTH_DIR, "wrangler.pid");
export const INSTALL_FILE = path.join(AUTH_DIR, "install.json");
export const LOG_FILE = path.join(STATE_DIR, "wrangler-dev.log");
// The public address uploaded pictures get. Nothing answers there: the suite's browser serves those
// addresses from the app's own /api/image-proxy (e2e/fixtures.js), which reads the local R2 bucket.
export const IMAGES_BASE = "https://images.example.test";

const WRANGLER = path.join(REPO, "node_modules", ".bin", "wrangler");

// wrangler.toml → a config that only works on this computer. Paths are made relative to e2e/.
export function localConfig(toml) {
  const lines = toml.split("\n");
  const out = [];
  let skip = false;
  for (const raw of lines) {
    const line = raw.trimEnd();
    const header = /^\s*\[{1,2}([^\]]+)\]{1,2}\s*$/.exec(line);
    if (header) skip = header[1].trim() === "ai" || header[1].trim() === "triggers";
    else if (skip && line.trim() === "") skip = false;   // each of those two blocks ends at its blank line
    if (skip) continue;
    // The R2 buckets the installer leaves commented out: switched on locally.
    const r2 = /^#\s*(\[\[r2_buckets\]\]|binding = "(IMAGES|RECEIPTS|DESIGNS)"|bucket_name = "opendecodesk-[a-z]+")\s*$/.exec(line);
    if (r2) { out.push(r2[1]); continue; }
    if (/^#\s*$/.test(line) && out.length && /bucket_name/.test(out[out.length - 1])) { out.push(""); continue; }
    out.push(line
      .replace(/^main = "src\/worker\.js"/, 'main = "../src/worker.js"')
      .replace(/^directory = "\.\/public"/, 'directory = "../public"')
      .replace(/^migrations_dir = "migrations"/, 'migrations_dir = "../migrations"')
      .replace(/^workers_dev = true/, "workers_dev = false"));
  }
  let text = out.join("\n");
  if (!/\[\[r2_buckets\]\]/.test(text)) throw new Error("Could not switch the R2 buckets on in the local config.");
  if (!/main = "\.\.\/src\/worker\.js"/.test(text) || !/directory = "\.\.\/public"/.test(text)) throw new Error("Could not rewrite the paths in the local config.");
  text = "# GENERATED by e2e/lib/install.mjs for the end-to-end suite — local only, never deployed. Do not edit or commit.\n" + text +
    "\n\n[vars]\nROOT_DOMAIN = \"localhost\"\nADMIN_SUBDOMAIN = \"admin\"\nTIMEZONE = \"UTC\"\nR2_PUBLIC_BASE = \"" + IMAGES_BASE + "\"\n";
  return text;
}

const secret = (n = 32) => crypto.randomBytes(n).toString("base64url");

export function writeLocalFiles() {
  fs.writeFileSync(CONFIG, localConfig(fs.readFileSync(path.join(REPO, "wrangler.toml"), "utf8")));
  const passphrase = "e2e-setup-" + secret(18);
  const vars = {
    PROXY_ADMIN_PASSPHRASE: passphrase,
    SIGNING_SECRET: secret(),
    LINK_SIGNING_SECRET: secret(),
    CRON_SECRET: secret(),
    VENDOR_CREDENTIALS_KEY: crypto.randomBytes(32).toString("base64"),
  };
  fs.writeFileSync(DEV_VARS, "# GENERATED test secrets for the local end-to-end install. Never real keys; never commit.\n" +
    Object.entries(vars).map(([k, v]) => k + '="' + v + '"').join("\n") + "\n", { mode: 0o600 });
  return { passphrase };
}

function run(args, label) {
  const r = spawnSync(WRANGLER, args, { cwd: REPO, encoding: "utf8", env: { ...process.env, CI: "1", WRANGLER_SEND_METRICS: "false" } });
  if (r.status !== 0) throw new Error(label + " failed (exit " + r.status + "):\n" + (r.stdout || "") + (r.stderr || ""));
  return (r.stdout || "") + (r.stderr || "");
}

export function buildDatabase() {
  fs.rmSync(STATE_DIR, { recursive: true, force: true });
  fs.mkdirSync(STATE_DIR, { recursive: true });
  const sqlFile = path.join(STATE_DIR, "fresh.sql");
  const sql = spawnSync(process.execPath, [path.join(REPO, "scripts", "setup.mjs"), "--print-fresh-sql"], { cwd: REPO, encoding: "utf8", maxBuffer: 64 << 20 });
  if (sql.status !== 0 || !/d1_migrations/.test(sql.stdout)) throw new Error("setup.mjs --print-fresh-sql failed:\n" + sql.stderr);
  fs.writeFileSync(sqlFile, sql.stdout);
  run(["d1", "execute", "DB", "--local", "--yes", "--config", CONFIG, "--persist-to", STATE_DIR, "--file", sqlFile], "Building the database");
  const out = run(["d1", "migrations", "apply", "DB", "--local", "--config", CONFIG, "--persist-to", STATE_DIR], "Applying migrations");
  if (!/No migrations to apply/i.test(out)) throw new Error("A fresh database should have every migration already; wrangler said:\n" + out);
}

export async function waitForServer(base, ms = 90_000) {
  const end = Date.now() + ms;
  let last = "";
  while (Date.now() < end) {
    try {
      const r = await fetch(base + "/api/catalog", { headers: { Host: "admin.localhost:" + PORT } });
      if (r.status < 500) return;
      last = "status " + r.status;
    } catch (e) { last = e.message; }
    await new Promise(r => setTimeout(r, 500));
  }
  throw new Error("wrangler dev did not answer on " + base + " (" + last + "). Log: " + LOG_FILE);
}

export async function startServer() {
  const log = fs.openSync(LOG_FILE, "a");
  const child = spawn(WRANGLER, ["dev", "--config", CONFIG, "--persist-to", STATE_DIR, "--port", String(PORT), "--ip", "127.0.0.1",
    "--local", "--show-interactive-dev-session=false", "--log-level", "warn"], {
    cwd: REPO, detached: true, stdio: ["ignore", log, log],
    env: { ...process.env, CI: "1", WRANGLER_SEND_METRICS: "false", NO_COLOR: "1" },
  });
  child.unref();
  fs.mkdirSync(AUTH_DIR, { recursive: true });
  fs.writeFileSync(PID_FILE, String(child.pid));
  await waitForServer("http://127.0.0.1:" + PORT);
  return child.pid;
}

export function stopServer() {
  let pid = 0;
  try { pid = Number(fs.readFileSync(PID_FILE, "utf8")); } catch (e) { return false; }
  if (!pid) return false;
  // wrangler dev starts workerd as a child: the whole process group goes.
  try { process.kill(-pid, "SIGTERM"); } catch (e) { try { process.kill(pid, "SIGTERM"); } catch (e2) {} }
  const end = Date.now() + 10_000;
  while (Date.now() < end) {
    try { process.kill(-pid, 0); } catch (e) { break; }
    spawnSync("sleep", ["0.2"]);
  }
  try { process.kill(-pid, "SIGKILL"); } catch (e) {}
  fs.rmSync(PID_FILE, { force: true });
  return true;
}

export function portInUse() {
  const r = spawnSync("lsof", ["-nP", "-iTCP:" + PORT, "-sTCP:LISTEN"], { encoding: "utf8" });
  return r.status === 0 && /LISTEN/.test(r.stdout);
}
